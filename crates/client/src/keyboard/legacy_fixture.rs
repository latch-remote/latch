// Verbatim input::vk from bf5da0d, Latch 6.0.0. Keep independent of current maps.
use crate::input::*;
use egui::Key;
pub fn vk(key: Key) -> Option<i16> {
    use Key::*;
    Some(match key {
        ArrowDown => 0x28,
        ArrowLeft => 0x25,
        ArrowRight => 0x27,
        ArrowUp => 0x26,
        Escape => VK_ESCAPE,
        Tab => VK_TAB,
        Backspace => 0x08,
        Enter => 0x0D,
        Space => 0x20,
        Insert => VK_INSERT,
        Delete => VK_DELETE,
        Home => 0x24,
        End => 0x23,
        PageUp => 0x21,
        PageDown => 0x22,
        Colon | Semicolon => 0xBA,
        Comma => 0xBC,
        Backslash | Pipe => 0xDC,
        Slash | Questionmark => 0xBF,
        Exclamationmark => 0x31,
        OpenBracket | OpenCurlyBracket => 0xDB,
        CloseBracket | CloseCurlyBracket => 0xDD,
        Backtick => 0xC0,
        Minus => 0xBD,
        Period => 0xBE,
        Equals => 0xBB,
        // egui's Plus comes from the keypad's + key alone (the main row's
        // key is Equals): VK_ADD types "+" there, VK_OEM_PLUS typed "=".
        Plus => 0x6B,
        Quote => 0xDE,
        Num0 => 0x30,
        Num1 => 0x31,
        Num2 => 0x32,
        Num3 => 0x33,
        Num4 => 0x34,
        Num5 => 0x35,
        Num6 => 0x36,
        Num7 => 0x37,
        Num8 => 0x38,
        Num9 => 0x39,
        A => 0x41,
        B => 0x42,
        C => 0x43,
        D => 0x44,
        E => 0x45,
        F => 0x46,
        G => 0x47,
        H => 0x48,
        I => 0x49,
        J => 0x4A,
        K => 0x4B,
        L => 0x4C,
        M => 0x4D,
        N => 0x4E,
        O => 0x4F,
        P => 0x50,
        Q => 0x51,
        R => 0x52,
        S => 0x53,
        T => 0x54,
        U => 0x55,
        V => 0x56,
        W => 0x57,
        X => 0x58,
        Y => 0x59,
        Z => 0x5A,
        F1 => 0x70,
        F2 => 0x71,
        F3 => 0x72,
        F4 => 0x73,
        F5 => 0x74,
        F6 => 0x75,
        F7 => 0x76,
        F8 => 0x77,
        F9 => 0x78,
        F10 => 0x79,
        F11 => 0x7A,
        F12 => 0x7B,
        F13 => 0x7C,
        F14 => 0x7D,
        F15 => 0x7E,
        F16 => 0x7F,
        F17 => 0x80,
        F18 => 0x81,
        F19 => 0x82,
        F20 => 0x83,
        F21 => 0x84,
        F22 => 0x85,
        F23 => 0x86,
        F24 => 0x87,
        _ => return None,
    })
}
